#!/usr/bin/env python3
"""Generate the typed message-key union from the default locale.

en_US/messages.json stays the source of truth -- the manifest needs __MSG_*
and default_locale either way, and the stores read the localised name and
description straight out of _locales. What is missing is any link between a
key and the code that uses it: WebDeveloper.Locales.getString takes a string,
so a typo returns "" and the label just renders empty.

Two unions come out of this rather than one. A message whose text contains a
placeholder is useless without its substitution -- getMessage leaves the
"$count$" in place -- so those keys are separated and t() overloads on them,
making the substitution required where it matters and rejected where it does
not.

Run after touching en_US/messages.json; the output is committed and CI checks
it is current.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "public" / "_locales" / "en_US" / "messages.json"
TARGET = ROOT / "src" / "lib" / "i18n-keys.ts"


def render() -> str:
    messages = json.loads(SOURCE.read_text(encoding="utf-8"))

    plain = sorted(key for key, value in messages.items() if not value.get("placeholders"))
    substituted = sorted(key for key, value in messages.items() if value.get("placeholders"))

    def union(keys: list[str]) -> str:
        if not keys:
            return "  never;"
        return "\n".join(f'  | "{key}"' for key in keys) + ";"

    return f"""// Generated by tools/generate-i18n-keys.py from
// src/public/_locales/en_US/messages.json. Do not edit by hand.

/** Messages taking no substitution. */
export type PlainMessageKey =
{union(plain)}

/** Messages whose text contains a placeholder, so a substitution is required. */
export type SubstitutedMessageKey =
{union(substituted)}

export type MessageKey = PlainMessageKey | SubstitutedMessageKey;

/**
 * Every key, at runtime. Lets the registry invariant test assert that each
 * labelKey it references actually exists, which the type alone cannot do for
 * keys built up from data.
 */
export const MESSAGE_KEYS: ReadonlySet<string> = new Set({json.dumps(sorted(messages), indent=2)});
"""


def main() -> int:
    wanted = render()
    check = "--check" in sys.argv

    if check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""

        if current != wanted:
            print(f"{TARGET.relative_to(ROOT)} is stale; run tools/generate-i18n-keys.py")
            return 1

        print(f"ok: {TARGET.relative_to(ROOT)} matches en_US")
        return 0

    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
