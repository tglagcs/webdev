import { defineConfig } from "wxt";
import tailwindcss from "@tailwindcss/vite";

import { HOMEPAGE_URL } from "./src/branding";

// Chrome-only permission. Its absence is why the whole Disable menu and
// Disable Cookies are hidden on Firefox -- see src/lib/capabilities.
const CHROME_ONLY_PERMISSIONS = ["contentSettings"];

const FIREFOX_EXTENSION_ID = "{3efc0a4d-187a-41c4-8c98-4ced451b523b}";

export default defineConfig({
  srcDir: "src",
  // Static assets that must keep stable URLs: the feature stylesheets injected
  // into host pages, the widget CSS, the locales, and the icons.
  // Resolved against the project root, not srcDir.
  publicDir: "src/public",
  modules: ["@wxt-dev/module-svelte"],

  // The about page used to show a @build.date@ token substituted by gulp.
  vite: () => ({
    plugins: [tailwindcss()],
    define: {
      __BUILD_DATE__: JSON.stringify(new Date().toISOString().slice(0, 10)),
    },
  }),

  // WXT still defaults Firefox to MV2. Upstream shipped MV3 to every browser
  // and the code is written against it, so pin it for both targets.
  manifestVersion: 3,

  manifest: ({ browser }) => {
    const chromium = browser !== "firefox";

    return {
      name: "__MSG_extensionName__",
      description: "__MSG_extensionDescription__",
      default_locale: "en_US",
      homepage_url: HOMEPAGE_URL,

      permissions: [
        "browsingData",
        "cookies",
        "history",
        "scripting",
        "storage",
        "tabs",
        ...(chromium ? CHROME_ONLY_PERMISSIONS : []),
      ],
      host_permissions: ["<all_urls>"],

      icons: icons(),
      action: {
        default_icon: icons(),
        default_title: "__MSG_extensionName__",
      },

      // options_ui is generated by WXT from the options entrypoint; its
      // open_in_tab comes from a <meta name="manifest.open_in_tab"> tag there.
      ...(chromium
        ? {}
        : {
            browser_specific_settings: {
              gecko: {
                id: FIREFOX_EXTENSION_ID,
                // 115 is the floor for storage.session, which holds the
                // per-tab feature state. 115 is also an ESR, so this drops
                // only the 109-114 window rather than a supported release.
                strict_min_version: "115.0",
                // AMO requires this to be declared. The extension sends
                // nothing anywhere; everything it reads stays on the device.
                data_collection_permissions: { required: ["none"] },
              },
            },
          }),

      web_accessible_resources: [
        {
          matches: ["<all_urls>"],
          resources: [
            "embedded/css/*.css",
            "embedded-dashboard.js",
            "features/css/*.css",
            "img/transparent.png",
            "lib/bootstrap/bootstrap.css",
            "lib/bootstrap/bootstrap.js",
            "lib/reset.css",
            "svg/logos/color/logo.svg",
          ],
          // Not supported on Firefox, and absent from upstream's Firefox
          // manifest for the same reason.
          ...(chromium ? { use_dynamic_url: true } : {}),
        },
      ],
    };
  },
});

function icons() {
  return Object.fromEntries(
    [16, 32, 48, 64, 128, 256].map((size) => [size, `/img/logos/color/${size}.png`]),
  );
}
